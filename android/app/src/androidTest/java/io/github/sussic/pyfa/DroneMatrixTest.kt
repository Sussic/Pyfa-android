/** Original-command output comparison, not expectations generated by the app. */
@RunWith(AndroidJUnit4::class)
class DroneMatrixTest {
    private val instrumentation get() = InstrumentationRegistry.getInstrumentation()
    private val context get() = instrumentation.targetContext
    private fun fit(id: String) = EngineRuntime.library.value.single { it.id == id }
    private fun details(id: String) = EngineRuntime.droneDetails(context,id).get(120,TimeUnit.SECONDS)
    private fun graph() = JSONObject(EngineRuntime.defensePersistenceSnapshot(context).get(120,TimeUnit.SECONDS))
    private fun send(op: BridgeOperation, ids: List<String>, ok: Boolean = true, stale: Boolean = false): BridgeResponse {
        val result=EngineRuntime.request(context,op,ids.associateWith { if(stale) 0L else fit(it).revision }).get(120,TimeUnit.SECONDS)
        assertEquals(result.error?.message,ok,result.isSuccess); return result
    }
    private fun spec(value: JSONObject): FitSpec {
        val pattern=value.getJSONObject("damage_pattern"); val security=value.getJSONObject("security")
        val modules=value.getJSONArray("modules"); val drones=value.getJSONArray("drones")
        return FitSpec(value.getString("name"),value.getString("ship"),value.getInt("skill_level"),value.getBoolean("factor_reload"),
            DamagePattern(pattern.getDouble("emAmount"),pattern.getDouble("thermalAmount"),pattern.getDouble("kineticAmount"),pattern.getDouble("explosiveAmount")),
            Security(SystemSecurity.valueOf(security.getString("system")),security.getDouble("pilot")),
            (0 until modules.length()).map { modules.getJSONObject(it).let { m -> ModuleSpec(m.getString("name"),
                ModuleState.valueOf(m.getString("state")),if(m.isNull("charge")) null else m.getString("charge")) } },
            (0 until drones.length()).map { drones.getJSONObject(it).let { d -> DroneSpec(d.getString("name"),d.getInt("amount"),d.getInt("active")) } })
    }
    private fun create(value: JSONObject): String {
        val id=send(BridgeOperation.CreateFit(spec(value)),emptyList()).fits.single().id
        send(BridgeOperation.SetFitRestrictions(id,false),listOf(id))
        return id
    }
    private fun operation(id: String, name: String, a: JSONObject): BridgeOperation = when(name) {
        "add_drone" -> BridgeOperation.AddDrone(id,a.getInt("item_id"),a.getInt("amount"))
        "add_drone_stack" -> BridgeOperation.AddDroneStack(id,a.getInt("item_id"))
        "set_drone_amount" -> BridgeOperation.SetDroneAmount(id,a.getInt("position"),a.getInt("amount"))
        "remove_drones" -> BridgeOperation.RemoveDrones(id,(0 until a.getJSONArray("positions").length()).map { a.getJSONArray("positions").getInt(it) },a.getInt("amount"))
        "toggle_drones" -> BridgeOperation.ToggleDrones(id,a.getInt("main_position"),(0 until a.getJSONArray("positions").length()).map { a.getJSONArray("positions").getInt(it) })
        "clone_drone" -> BridgeOperation.CloneDrone(id,a.getInt("position"))
        "change_variation" -> BridgeOperation.ChangeVariation(id,VariationContext.DRONE,a.getInt("position"),a.getInt("item_id"))
        else -> error("Unexpected original operation $name")
    }
    private fun core(id: String): JSONObject {
        val d=details(id)
        fun sum(key: String)=d.stacks.sumOf { stack -> stack.metrics.single { it.key==key }.value ?: 0.0 }
        fun damage(prefix: String)=JSONObject().apply { listOf("em","thermal","kinetic","explosive","total").forEach { put(it,sum(prefix+"_"+it)) } }
        return obj("drones" to array(d.stacks.map { obj("name" to it.name,"item_id" to it.itemId,"amount" to it.amount,"active" to it.active) }),
            "active" to d.active,"bay" to d.bayUsed,"bandwidth" to d.bandwidthUsed,"dps" to damage("dps"),"volley" to damage("volley"),"mining" to sum("mining_yield"))
    }
    private fun report(id: String): JSONObject {
        val names=setOf("range","falloff","trackingSpeed","maxVelocity","volume","droneBandwidthUsed")
        return obj("core" to core(id),"stats" to ModuleTestJson.stats(fit(id)),"attributes" to array(details(id).stacks.map { s ->
            JSONObject().apply { s.metrics.filter { it.key in names }.forEach { put(it.key,it.value ?: JSONObject.NULL) } } }))
    }
    private fun original(name: String): JSONObject {
        assertEquals(1,Settings.Global.getInt(context.contentResolver,Settings.Global.AIRPLANE_MODE_ON))
        assertEquals(PackageManager.PERMISSION_DENIED,context.checkSelfPermission(Manifest.permission.INTERNET))
        EngineRuntime.start(context).get(120,TimeUnit.SECONDS)
        val expected=JSONObject(instrumentation.context.assets.open(name).bufferedReader().use { it.readText() })
        val runtime=JSONObject(EngineRuntime.bridgeDiagnostics(context).get(120,TimeUnit.SECONDS))
        assertEquals("8b04f3b271e614b3e103853b44a7851a63d79d0e",expected.getString("source_commit"))
        assertEquals(expected.getString("database_sha256"),runtime.getJSONObject("manifest").getString("database_sha256"))
        if(expected.has("eos_settings")) compare(expected.getJSONObject("eos_settings"),runtime.getJSONObject("eos_settings"),strict=false)
        assertEquals(0,runtime.getJSONArray("desktop_import_attempts").length())
        return expected
    }
    private fun rejected(id: String, op: BridgeOperation, stale: Boolean = false) {
        val before=graph(); val snapshots=EngineRuntime.library.value
        val states=snapshots.associate { it.id to details(it.id) }
        val history=snapshots.associate { it.id to EngineRuntime.editHistory(context,it.id).get(120,TimeUnit.SECONDS) }
        val store=File(context.noBackupFilesDir,"fits/graph.sqlite3"); val bytes=store.readBytes()
        send(op,listOf(id),ok=false,stale=stale)
        compare(before,graph()); assertEquals(snapshots,EngineRuntime.library.value); assertArrayEquals(bytes,store.readBytes())
        states.forEach { (key,value) -> assertEquals(value,details(key)) }
        history.forEach { (key,value) -> assertEquals(value,EngineRuntime.editHistory(context,key).get(120,TimeUnit.SECONDS)) }
    }
    @Test fun originalCoreCommandsAndHullBoundariesOffline() {
        val base=original("drone-core-edits-expected.json")
        val extras=original("drone-acceptance-expected.json").getJSONArray("core_extra")
        val cases=base.getJSONArray("cases"); val rows=JSONArray(); val covered=mutableSetOf<String>()
        for(i in 0 until cases.length()+extras.length()) {
            val case=if(i<cases.length()) cases.getJSONObject(i) else extras.getJSONObject(i-cases.length())
            val id=create(case.getJSONObject("spec")); val name=case.getString("operation")
            val op=operation(id,name,case.getJSONObject("arguments")); val before=details(id)
            compare(case.getJSONObject("before"),core(id),strict=false)
            val observed=obj("name" to case.getJSONObject("spec").getString("name"),"operation" to name,"before" to core(id))
            if(case.optBoolean("accepted",true)) {
                rejected(id,op,stale=true); send(op,listOf(id)); compare(case.getJSONObject("after"),core(id),strict=false)
                val after=details(id); observed.put("after",core(id))
                send(BridgeOperation.Undo(id),listOf(id)); compare(case.getJSONObject("restored"),core(id),strict=false)
                assertEquals(before.stacks,details(id).stacks); observed.put("restored",core(id))
                send(BridgeOperation.Redo(id),listOf(id)); compare(case.getJSONObject("after"),core(id),strict=false)
                assertEquals(after.stacks,details(id).stacks); observed.put("redone",core(id))
            } else { rejected(id,op); observed.put("after",core(id)).put("restored",core(id)) }
            observed.put("accepted",case.optBoolean("accepted",true)); rows.put(observed); covered.add(name)
            send(BridgeOperation.DeleteFit(id,true),listOf(id))
        }
        assertEquals(setOf("add_drone","add_drone_stack","set_drone_amount","remove_drones","toggle_drones","clone_drone"),covered)
        assertEquals(18,rows.length())
        File(context.noBackupFilesDir,"c04-core-observed.json").writeText(rows.toString(2))
    }

    @Test fun originalLinkedRecipientsAndOrdinaryVariationsOffline() {
        val expected=original("drone-acceptance-expected.json"); val cases=expected.getJSONArray("linked")
        val linked=JSONArray(); val variations=JSONArray()
        for(i in 0 until cases.length()) {
            val case=cases.getJSONObject(i); val owner=create(case.getJSONObject("spec")); val ids=mutableListOf(owner)
            val recipients=case.getJSONArray("recipients")
            for(j in 0 until recipients.length()) {
                val target=create(recipients.getJSONObject(j)); ids.add(target)
                compare(case.getJSONArray("unlinked").getJSONObject(j),report(target),strict=false)
                send(if(case.getString("link")=="command") BridgeOperation.AddCommand(owner,target)
                    else BridgeOperation.AddProjection(owner,target,0.0,true,1),listOf(owner,target))
            }
            val unrelated=create(JSONObject(recipients.getJSONObject(0).toString()).put("name","C04 unrelated $i"))
            val unrelatedBefore=fit(unrelated)
            fun reports()=array(ids.map { report(it) })
            compare(case.getJSONArray("before"),reports(),strict=false)
            val before=ids.associateWith { details(it).stacks }; val revisions=ids.associateWith { fit(it).revision }
            val op=operation(owner,case.getString("operation"),case.getJSONObject("arguments"))
            rejected(owner,op,stale=true); rejected(owner,BridgeOperation.CloneDrone(owner,999))
            val response=send(op,listOf(owner)); assertEquals(ids.toSet(),response.fits.map { it.id }.toSet())
            ids.forEach { assertEquals(revisions.getValue(it)+1,fit(it).revision) }
            assertEquals(unrelatedBefore,fit(unrelated)); compare(case.getJSONArray("after"),reports(),strict=false)
            val row=obj("name" to case.getJSONObject("spec").getString("name"),"operation" to case.getString("operation"),
                "link" to case.getString("link"),"after" to reports())
            val after=ids.associateWith { details(it).stacks }
            val undo=send(BridgeOperation.Undo(owner),listOf(owner))
            assertEquals(EngineRuntime.library.value.map { it.id }.toSet(),undo.fits.map { it.id }.toSet())
            compare(case.getJSONArray("restored"),reports(),strict=false); before.forEach { (id,value) -> assertEquals(value,details(id).stacks) }
            row.put("restored",reports())
            val redo=send(BridgeOperation.Redo(owner),listOf(owner))
            assertEquals(EngineRuntime.library.value.map { it.id }.toSet(),redo.fits.map { it.id }.toSet())
            compare(case.getJSONArray("after"),reports(),strict=false); after.forEach { (id,value) -> assertEquals(value,details(id).stacks) }
            row.put("redone",reports()); linked.put(row)
            for(id in ids.reversed()+unrelated) send(BridgeOperation.DeleteFit(id,true),listOf(id))
        }
        val rows=expected.getJSONArray("variations")
        for(i in 0 until rows.length()) {
            val case=rows.getJSONObject(i); val id=create(case.getJSONObject("spec")); val steps=case.getJSONArray("steps")
            for(j in 0 until steps.length()) {
                val step=steps.getJSONObject(j); val before=details(id).stacks
                compare(step.getJSONObject("before"),report(id),strict=false)
                send(operation(id,"change_variation",step.getJSONObject("arguments")),listOf(id))
                compare(step.getJSONObject("after"),report(id),strict=false)
                val after=details(id).stacks
                if(step.getBoolean("changed")) {
                    send(BridgeOperation.Undo(id),listOf(id)); compare(step.getJSONObject("restored"),report(id),strict=false)
                    assertEquals(before,details(id).stacks)
                    send(BridgeOperation.Redo(id),listOf(id)); assertEquals(after,details(id).stacks)
                }
                variations.put(obj("name" to case.getJSONObject("spec").getString("name"),"step" to j,"after" to report(id)))
            }
            rejected(id,BridgeOperation.ChangeVariation(id,VariationContext.DRONE,0,587))
            rejected(id,BridgeOperation.ChangeVariation(id,VariationContext.DRONE,999,2454))
            send(BridgeOperation.DeleteFit(id,true),listOf(id))
        }
        assertEquals(14,linked.length()); assertEquals(6,variations.length())
        File(context.noBackupFilesDir,"c04-linked-observed.json").writeText(obj("linked" to linked,"variations" to variations).toString(2))
    }

    private fun conservationReport(id: String, keys: JSONArray): JSONObject = obj("core" to core(id),
        "stats" to ModuleTestJson.stats(fit(id)), "metrics" to array(details(id).stacks.map { s ->
            JSONObject().apply { for(i in 0 until keys.length()) {
                val key=keys.getString(i); put(key,s.metrics.single { it.key==key }.value ?: JSONObject.NULL)
            } } }))
    private fun conservedDetails(): JSONObject = JSONObject().apply {
        EngineRuntime.library.value.forEach { f -> put(f.id,obj("revision" to f.revision,
            "stacks" to array(details(f.id).stacks.map { s -> obj("id" to s.objectKey,"item" to s.itemId,
                "amount" to s.amount,"active" to s.active,"mutation" to s.mutation?.let { m -> obj(
                    "base" to m.baseItemId,"mutaplasmid" to m.mutaplasmidId,
                    "rolls" to array(m.rolls.map { obj("id" to it.attributeId,"value" to it.value) })) },
                "metrics" to array(s.metrics.map { obj("key" to it.key,"unit" to it.unit,"value" to it.value) })) }))) }
    }
    @Test fun approvedConservationAndRestartOffline() {
        val expected=original("drone-conservation-expected.json")
        assertEquals("F08.03-conserve-v1",expected.getJSONObject("policy").getString("id"))
        val phase=InstrumentationRegistry.getArguments().getString("c04_phase") ?: error("Missing phase")
        val runtime=JSONObject(EngineRuntime.bridgeDiagnostics(context).get(120,TimeUnit.SECONDS))
        assertTrue(runtime.getJSONObject("persistence").getBoolean("opened_existing"))
        val saved=File(context.noBackupFilesDir,"c04-conservation-observed.json")
        if(phase=="conservation-restored") {
            val previous=JSONObject(saved.readText())
            assertNotEquals(previous.getInt("pid"),android.os.Process.myPid())
            assertNotEquals(previous.getJSONObject("runtime").getString("session_id"),runtime.getString("session_id"))
            compare(previous.getJSONObject("graph"),graph(),strict=false)
            compare(previous.getJSONObject("details"),conservedDetails(),strict=false)
            File(context.noBackupFilesDir,"c04-conservation-restored.json").writeText(obj("pid" to android.os.Process.myPid(),
                "prior_pid" to previous.getInt("pid"),"runtime" to runtime,"graph" to graph(),"details" to conservedDetails()).toString(2))
            return
        }
        assertEquals("conservation",phase)
        val cases=expected.getJSONArray("cases");val rows=JSONArray();val metrics=expected.getJSONArray("metrics")
        assertEquals(14,cases.length());assertEquals(14,EngineRuntime.library.value.size)
        for(i in 0 until cases.length()) {
            val case=cases.getJSONObject(i);val name=case.getJSONObject("spec").getString("name")
            val id=EngineRuntime.library.value.single { it.name==name }.id
            send(BridgeOperation.SetFitRestrictions(id,false),listOf(id))
            val before=details(id);val args=case.getJSONObject("arguments")
            val op=if(case.getString("operation")=="split_drone") BridgeOperation.SplitDrone(id,args.getInt("position"),args.getInt("amount"))
                else BridgeOperation.MergeDrones(id,args.getInt("source_position"),args.getInt("destination_position"))
            compare(case.getJSONObject("before"),conservationReport(id,metrics),strict=false)
            val row=obj("name" to name,"operation" to case.getString("operation"),"accepted" to case.getBoolean("accepted"),
                "before" to conservationReport(id,metrics))
            rejected(id,op,stale=true);rejected(id,BridgeOperation.MergeDrones(id,0,0))
            if(case.getBoolean("accepted")) {
                val unaffected=EngineRuntime.library.value.filter { it.id!=id }
                send(op,listOf(id));compare(case.getJSONObject("after"),conservationReport(id,metrics),strict=false)
                val after=details(id);assertEquals(before.active,after.active)
                assertEquals(before.stacks.sumOf { it.amount.toLong() },after.stacks.sumOf { it.amount.toLong() })
                assertEquals(unaffected,EngineRuntime.library.value.filter { it.id!=id })
                if(op is BridgeOperation.SplitDrone) {
                    assertEquals(before.stacks.map { it.objectKey },after.stacks.dropLast(1).map { it.objectKey })
                    assertFalse(after.stacks.last().objectKey in before.stacks.map { it.objectKey })
                    assertEquals(before.stacks[op.position].mutation,after.stacks.last().mutation)
                } else {
                    val merge=op as BridgeOperation.MergeDrones
                    assertEquals(before.stacks.filterIndexed { index,_ -> index!=merge.sourcePosition }.map { it.objectKey },after.stacks.map { it.objectKey })
                }
                row.put("after",conservationReport(id,metrics))
                send(BridgeOperation.Undo(id),listOf(id));assertEquals(before.stacks,details(id).stacks)
                compare(case.getJSONObject("before"),conservationReport(id,metrics),strict=false);row.put("restored",conservationReport(id,metrics))
                send(BridgeOperation.Redo(id),listOf(id));assertEquals(after.stacks,details(id).stacks)
                compare(case.getJSONObject("after"),conservationReport(id,metrics),strict=false);row.put("redone",conservationReport(id,metrics))
            } else {
                rejected(id,op);row.put("after",conservationReport(id,metrics)).put("restored",conservationReport(id,metrics))
            }
            rows.put(row)
        }
        val overflowSpec=JSONObject(cases.getJSONObject(0).getJSONObject("spec").toString()).put("name","C04 overflow")
        overflowSpec.put("drones",array(listOf(obj("name" to "Hobgoblin I","amount" to Int.MAX_VALUE,"active" to 0),
            obj("name" to "Hobgoblin I","amount" to 1,"active" to 0))))
        val overflow=create(overflowSpec)
        rejected(overflow,BridgeOperation.MergeDrones(overflow,0,1))
        send(BridgeOperation.DeleteFit(overflow,true),listOf(overflow))
        saved.writeText(obj("pid" to android.os.Process.myPid(),"runtime" to runtime,"cases" to rows,
            "graph" to graph(),"details" to conservedDetails()).toString(2))
    }

